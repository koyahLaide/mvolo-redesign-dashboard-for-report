// Nu importeren in DB
console.log('\n=== IMPORTEREN IN DB ===');
const insertOrder = db.prepare(`
  INSERT OR IGNORE INTO orders (
    id, order_number, created_at, total_price, channel,
    shipping_country, financial_status
  ) VALUES (?, ?, ?, ?, 'bol_marketplace', ?, 'paid')
`);

const insertItem = db.prepare(`
  INSERT OR REPLACE INTO order_items (
    order_id, sku, title, quantity, price, marketplace, channel
  ) VALUES (?, ?, ?, ?, ?, 'bol', 'bol_marketplace')
`);

const importAll = db.transaction(() => {
  let imported = 0;
  let skipped = 0;

  BOL_ORDERS.forEach(([date, product, price, qty, country], idx) => {
    if (!price) { skipped++; return; }

    const orderId = `bol_import_${date}_${idx}`;
    const orderNum = `BOL-${date.replace(/-/g,'')}-${idx}`;

    try {
      insertOrder.run(orderId, orderNum, date + 'T12:00:00Z', price * qty, country);
      const slug = product.toLowerCase().replace(/[^a-z0-9]/g, '-').replace(/-+/g, '-');
      insertItem.run(orderId, `BOL-${slug}`.substring(0,50), product, qty, price);
      imported++;
    } catch(e) {
      skipped++;
    }
  });

  return { imported, skipped };
});

const result = importAll();
console.log(`Geïmporteerd: ${result.imported} orders`);
console.log(`Overgeslagen: ${result.skipped} orders`);

